#!/usr/bin/env bash
# Overload experiment (PLAN §26.4): clustered prod nodes on the bench Postgres, an open-loop
# paced load, and a database that turns slow in the middle of the run and recovers.
#
#   bench/overload.sh --label after                      # this tree
#   SERVER_DIR=/path/to/worktree bench/overload.sh --label before
#
# The bottleneck is a trigger on `invocations` that sleeps per updated row while a flag row
# says so (`bench_throttle.sleep_ms`): a group commit then costs time in proportion to the
# builds it carries, as it does on a volume at its IOPS limit. Three phases: healthy,
# throttled, recovered; arrivals continue at the same rate through all of them.
#
# Options: --sleep-ms 400 (per row while throttled) --rate 20 (builds/s) --healthy-s 40
#          --overload-s 120 --recover-s 120 --nodes 2 --shards 4 --delay-ms 500 --retries 5
#          --retry-delay-ms 1000 (Bazel's backoff: 1.6 times longer per failed attempt)
# Any INGEST_*/ADMISSION*/RAW_LOG* variable in the environment reaches the nodes.
# Output: bench/results/overload-<label>/ (loadgen.json, metrics.tsv, phases, rows, node
# logs); summarize with bench/overload_report.py <dir>. The node logs are 10 MB each: keep
# the summary, not the directory. Do not edit this file while a run is in progress.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SERVER_DIR="${SERVER_DIR:-$ROOT}"
LABEL=run SLEEP_MS=400 RATE=20 HEALTHY=40 OVERLOAD=120 RECOVER=120 NODES=2 SHARDS=4 DELAY=500 RETRIES=5 RETRY_DELAY=1000
while [ $# -gt 0 ]; do
  case "$1" in
    --label) LABEL=$2 ;; --sleep-ms) SLEEP_MS=$2 ;; --rate) RATE=$2 ;; --healthy-s) HEALTHY=$2 ;;
    --overload-s) OVERLOAD=$2 ;; --recover-s) RECOVER=$2 ;; --nodes) NODES=$2 ;; --shards) SHARDS=$2 ;;
    --delay-ms) DELAY=$2 ;; --retries) RETRIES=$2 ;; --retry-delay-ms) RETRY_DELAY=$2 ;; *) echo "unknown option $1"; exit 1 ;;
  esac
  shift 2
done

OUT="$ROOT/bench/results/overload-$LABEL"
rm -rf "$OUT"; mkdir -p "$OUT"
export BENCH_PG_PORT="${BENCH_PG_PORT:-5441}"
DB=conveyor_overload
psql() { "$ROOT/bench/pg.sh" psql -v ON_ERROR_STOP=1 -Atq "$@"; }
"$ROOT/bench/pg.sh" start >/dev/null

export MIX_ENV=prod
export DATABASE_URL="ecto://postgres@127.0.0.1:${BENCH_PG_PORT}/$DB"
export SECRET_KEY_BASE="bench-secret-key-base-bench-secret-key-base-bench-secret-key-base-0000"
export PHX_SERVER=true PHX_HOST=localhost BES_INGEST_AUTH=none METRICS_TOKEN=bench
export BLOB_DIR="$ROOT/tmp/blobs_overload" POOL_SIZE="${POOL_SIZE:-20}"
export ERL_FLAGS="+sbwt none +sbwtdcpu none +sbwtdio none"
export INGEST_WRITER_SHARDS="$SHARDS"

psql -c "DROP DATABASE IF EXISTS $DB WITH (FORCE)" -c "CREATE DATABASE $DB" >/dev/null
(cd "$SERVER_DIR" && CLUSTER_STRATEGY=none mix ecto.migrate --quiet)
psql -d "$DB" >/dev/null <<'SQL'
CREATE TABLE bench_throttle (sleep_ms integer NOT NULL);
INSERT INTO bench_throttle VALUES (0);
CREATE FUNCTION bench_throttle() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE ms integer;
BEGIN
  SELECT sleep_ms INTO ms FROM bench_throttle;
  IF ms > 0 THEN PERFORM pg_sleep(ms / 1000.0); END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER bench_throttle AFTER UPDATE ON invocations
  FOR EACH ROW EXECUTE FUNCTION bench_throttle();
SQL

HOST="$(hostname -s)"
CLUSTER=""; HOSTS=""
for i in $(seq 1 "$NODES"); do
  CLUSTER="${CLUSTER:+$CLUSTER,}ovl$i@$HOST"; HOSTS="${HOSTS:+$HOSTS,}127.0.0.1:$((1990 + i))"
done

PIDS=()
cleanup() { for p in "${PIDS[@]:-}"; do kill "$p" 2>/dev/null || true; done; pkill -f "sname ovl" 2>/dev/null || true; }
trap cleanup EXIT

for i in $(seq 1 "$NODES"); do
  (cd "$SERVER_DIR" && PORT=$((4190 + i)) GRPC_PORT=$((1990 + i)) CLUSTER_STRATEGY=epmd CLUSTER_HOSTS="$CLUSTER" \
     exec elixir --sname "ovl$i" --cookie ovl -S mix phx.server >"$OUT/node$i.log" 2>&1) &
  PIDS+=($!)
done
for i in $(seq 1 "$NODES"); do
  for _ in $(seq 1 120); do curl -sf "localhost:$((4190 + i))/health/ready" >/dev/null && break; sleep 1; done
  curl -sf "localhost:$((4190 + i))/health/ready" >/dev/null || { echo "node $i did not come up"; exit 1; }
done

# One line per node and series every 5 s: epoch, node, series, value.
scrape() {
  while true; do
    now=$(date +%s)
    for i in $(seq 1 "$NODES"); do
      curl -s -m 4 "localhost:$((4190 + i))/metrics?token=bench" \
        | grep -E '^conveyor_(admission|ingest_writer_backlog|ingest_writer_expired|ingest_fenced|ingest_streams|ingest_workers|ingest_ack_count|ingest_ack_resent|ingest_writer_group_failed)' \
        | awk -v t="$now" -v n="$i" '{print t "\t" n "\t" $1 "\t" $2}' >>"$OUT/metrics.tsv" || true
    done
    sleep 5
  done
}
scrape & PIDS+=($!)

TOTAL=$((HEALTHY + OVERLOAD + RECOVER))
echo "label=$LABEL server=$(cd "$SERVER_DIR" && git rev-parse --short HEAD) sleep_ms=$SLEEP_MS rate=$RATE nodes=$NODES shards=$SHARDS delay_ms=$DELAY retries=$RETRIES retry_delay_ms=$RETRY_DELAY load=$(uptime | sed 's/.*averages: //')" | tee "$OUT/params"
(cd "$ROOT" && CLUSTER_STRATEGY=none mix conveyor.loadgen --hosts "$HOSTS" --arrival-rate "$RATE" --duration-s "$TOTAL" \
   --delay-ms "$DELAY" --jitter-ms 500 --retries "$RETRIES" --retry-delay-ms "$RETRY_DELAY" --report "$OUT/loadgen.json" >"$OUT/loadgen.log" 2>&1 || true) &
LOADGEN=$!

sleep "$HEALTHY"
echo "throttle_on $(date +%s)" | tee -a "$OUT/phases"
psql -d "$DB" -c "UPDATE bench_throttle SET sleep_ms = $SLEEP_MS"
sleep "$OVERLOAD"
echo "throttle_off $(date +%s)" | tee -a "$OUT/phases"
psql -d "$DB" -c "UPDATE bench_throttle SET sleep_ms = 0"
wait "$LOADGEN"
echo "loadgen_done $(date +%s)" | tee -a "$OUT/phases"
sleep 12
psql -d "$DB" -F ' ' -c "SELECT 'rows', status, count(*) FROM invocations GROUP BY 2 ORDER BY 2" | tee "$OUT/rows"
head -4 "$OUT/loadgen.log"
